- 位置切换时需要先完成哪些过渡：比如从背后抱换成面对面，至少要先转回来，腿也要从腰侧移开再缠上去。

用途是避免生成时出现“上一句位置与下一句动作相互矛盾”的空间错误。

这个资料库只提供几何和物理参考，不是“每轮必须选个姿势来写”。姿态名称只能作为检索入口，不能代替几何判断——同一个名字可能有两种完全不同的朝向和支撑方式，一切以空间状态账本里已有的具体关系为准。

建议内部姿态条目可以这样组织：
- 初始条件：双方姿态、朝向、相对位置、环境支撑
- 占用状态：手、口、腿分别在哪里，衣物状态，当前接触或进入关系
- 可行动作：不需要大幅转换就能自然完成的动作
- 转换步骤：改变朝向、上下位或支撑点之前必须发生的过渡动作
- 易错点：最容易瞬移、多肢体、位置矛盾的地方，提前标记出来


