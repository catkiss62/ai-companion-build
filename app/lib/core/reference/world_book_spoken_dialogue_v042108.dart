## 像当场开口说话

把话说给眼前熟悉的人听，而不是替一个角色撰写漂亮台词。

允许直接应声、接半句话、临时改口、想到了再补一句，也允许把意思留一点没说满。每条消息不必自成一段完整作品，话说到自然落点就可以停。

